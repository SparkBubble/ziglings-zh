//
// Zig 语言正在快速发展，语言结构也在不断改进。Ziglings 随之演进。
//
// 在 0.11 版之前，Zig 的 'for' 循环无法直接实现 C 风格的 "for(a;b;c)"，
// 而这种形式很适合遍历数字序列。
//
// 当时只能用带计数器的 'while' 循环笨拙地替代：
//
//     var i: usize = 0;
//     while (i < 10) : (i += 1) {
//         // 这里变量 'i' 会依次取值 0 到 9。
//     }
//
// 但现在我们已经进入美好的未来，Zig 的 'for' 循环可以这样写：
//
//     for (0..10) |i| {
//         // 这里变量 'i' 会依次取值 0 到 9。
//     }
//
// 理解这个例子的关键是知道 '0..9' 使用了新的范围语法：
//
//     0..10 表示从 0 到 9 的范围
//     1..4  表示从 1 到 3 的范围
//
//     重要的是，结束值不包含在范围内。
//
// 目前，只有 'for' 循环支持使用范围。
//
// 还记得练习 13 吗？当时我们这样打印数字序列：
//
//     var n: u32 = 1;
//
//     // 我想打印 1 到 20 之间不能被 3 或 5 整除的所有数字。
//     while (n <= 20) : (n += 1) {
//         // '%' 符号是“取模”运算符，会返回除法的余数。
//         if (n % 3 == 0) continue;
//         if (n % 5 == 0) continue;
//         std.debug.print("{} ", .{n});
//     }
//
//  来试试用新的 'for' 循环形式重写那个练习：
//
const std = @import("std");

pub fn main() void {

    // 我想打印 1 到 20 之间不能被 3 或 5 整除的所有数字。
    for (???) |n| {

        // '%' 符号是“取模”运算符，会返回除法的余数。
        if (n % 3 == 0) continue;
        if (n % 5 == 0) continue;
        std.debug.print("{} ", .{n});
    }

    std.debug.print("\n", .{});

    // 我们也打印从 1 到 15 的所有数字。
    for (???) |n| {
        std.debug.print("{} ", .{n});
    }
    std.debug.print("\n", .{});
}
