//
// 位操作是非常强大的工具，Zig 也不例外。
// 自计算机时代开始以来，人们开发了许多仅通过移动、设置或逻辑组合位
// 来解决问题的算法。
//
// Zig 标准库也会在适合的地方直接使用位操作，基于整数的计算也经常可以这样实现。
//
// 乍看之下，如果内存区域中只有“数字”在变化，往往很难理解算法究竟做了什么。
// 但别忘了，数字只是对位序列的一种解释。
//
// 这与我们通常的做法几乎相反：我们平时是用位序列来表示数字。
//
// 记住：1 字节 = 8 位 = 11111111（二进制）= 255（十进制）= FF（十六进制）。
//
// Zig 提供了更改变量内部位的必要操作，并区分位变化是否会导致溢出。
// 详情请参阅 Zig 文档中的“运算符表”一节。
//
// 以下是更改变量中各位的一些示例：
//
//          const numOne: u8 = 15;        //   =  0000 1111
//          const numTwo: u8 = 245;       //   =  1111 0101
//
//          const res1 = numOne >> 4;     //   =  0000 0000 - 右移
//          const res2 = numOne << 4;     //   =  1111 0000 - 左移
//          const res3 = numOne & numTwo; //   =  0000 0101 - 与
//          const res4 = numOne | numTwo; //   =  1111 1111 - 或
//          const res5 = numOne ^ numTwo; //   =  1111 1010 - 异或
//
//
// 为了熟悉位操作，我们先从一个简单但常被低估的功能开始，
// 然后大致按顺序继续其他练习。
//
// 以下文字摘自维基百科。
//
// 交换
// 在计算机编程中，交换两个变量指的是互换它们的值。通常，这是通过操作
// 内存中的数据实现的。例如，程序中可以这样定义两个变量（伪代码）：
//
//                        data_item x := 1
//                        data_item y := 0
//
//                        swap (x, y);
//
// 执行 swap() 后，x 的值为 0，y 的值为 1；它们的值互换了。
// 交换两个变量最简单、也许最常见的方法是使用第三个临时变量：
//
//                        define swap (x, y)
//                        temp := x
//                        x := y
//                        y := temp
//
// 不过，对于整数，也可以仅用位操作实现交换。只需用异或将两个变量相互组合，
// 就能得到相同结果。

const std = @import("std");
const print = std.debug.print;

pub fn main() !void {

    // 令 x 和 y 的值分别为 1101 和 1011
    var x: u8 = 0b1101;
    var y: u8 = 0b1011;

    // 现在用异或操作交换两个变量的值
    x ^= y;
    y ^= x;

    // 这里应该写什么？
    ???;

    print("x = {b}; y = {b}\n", .{ x, y });
}

// 这种变量交换利用了这样一个事实：两个值异或后的结果包含了这两个值的信息。
// 过去（现在也仍然）有时会利用这一点进行加密：值 XOR 密钥 = 密文，
// 因此密文 XOR 密钥 = 原值。由于异或运算可以交换顺序，也能用它交换两个变量。
